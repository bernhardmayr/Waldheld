export interface WerkstattWort {
  wort: string;
  /** Lücken-Übung: vor + [Option] + nach */
  luecke?: { vor: string; nach: string; optionen: string[]; richtig: string };
  hinweis?: string;
  silben?: string[];
}
export interface Schwerpunkt {
  id: string;
  titel: string;
  regel: string;
  woerter: WerkstattWort[];
}

const l = (
  wort: string,
  vor: string,
  richtig: string,
  nach: string,
  optionen: string[],
  hinweis?: string,
): WerkstattWort => ({
  wort,
  luecke: { vor, nach, optionen, richtig },
  ...(hinweis ? { hinweis } : {}),
});

